
package com.example.attendance.ai;

import com.google.genai.Client;
import com.google.genai.types.GenerateContentResponse;
import org.springframework.stereotype.Service;

@Service
public class GeminiAiService {

    private final Client client;

    public GeminiAiService() {

        String apiKey = System.getenv("GEMINI_API_KEY");

        if (apiKey == null || apiKey.isBlank()) {
            // AI key is optional. Do not stop the application.
            this.client = null;
            return;
        }

        this.client = Client.builder()
                .apiKey(apiKey)
                .build();
    }

    public String generateResponse(String prompt) {

        if (prompt == null || prompt.isBlank()) {
            return "Please enter a valid question.";
        }

        if (client == null) {
            return "AI Assistant is currently unavailable because the Gemini API key is not configured.";
        }

        String cleanPrompt = prompt.trim();

        try {
            return generateWithModel(
                    "gemini-3.8-flash",
                    cleanPrompt
            );

        } catch (Exception primaryException) {

            try {
                return generateWithModel(
                        "gemini-3.7-flash",
                        cleanPrompt
                );

            } catch (Exception fallbackException) {
                return "AI service is temporarily unavailable. Please try again later.";
            }
        }
    }

    private String generateWithModel(
            String model,
            String prompt) {

        GenerateContentResponse response =
                client.models.generateContent(
                        model,
                        prompt,
                        null
                );

        String text = response.text();

        if (text == null || text.isBlank()) {
            throw new IllegalStateException(
                    "No response was generated by " + model
            );
        }

        return text.trim();
    }
}
